function R_dot = getR0_6dotMatrix(q_pos,q_vel)

	C1 = cos(q_pos(1));
	C4 = cos(q_pos(4));
	C5 = cos(q_pos(5));
	C6 = cos(q_pos(6));

	S1 = sin(q_pos(1));
	S4 = sin(q_pos(4));
	S5 = sin(q_pos(5));
	S6 = sin(q_pos(6));

	C2p3 = cos(q_pos(2) + q_pos(3));
	S2p3 = sin(q_pos(2) + q_pos(3));
	
	qd1 = q_vel(1);
	qd2 = q_vel(2);
	qd3 = q_vel(3);
	qd4 = q_vel(4);
	qd5 = q_vel(5);
	qd6 = q_vel(6);

    R_dot = zeros(3,3);
    
	R_dot(1,1) = -(C1 * (C5*C6*S4 + C4*S6) * qd1) + S1 * (C6*S2p3*S5 + C2p3 * (-(C4*C5*C6) + S4*S6)) * qd1 ...
		- S1 * ((C4*C5*C6 - S4*S6) * qd4 - C6*S4*S5 * qd5 + (C4*C6 - C5*S4*S6) * qd6) + C1 * (-(C2p3*C6*S5 * (qd2 + qd3)) ...
		- S2p3 * (C4*C5*C6 - S4*S6) * (qd2 + qd3) - C5*C6*S2p3 * qd5 + S2p3*S5*S6 * qd6 - C2p3 * ((C5*C6*S4 + C4*S6) * qd4 ...
		+ C4*C6*S5 * qd5 + (C6*S4 + C4*C5*S6) * qd6));
	R_dot(1,2) = -(C6 * ((C1*C4 - C2p3*S1*S4) * qd1 - C1*S2p3*S4 * (qd2 + qd3) + (C1*C2p3*C4 - S1*S4) * qd4)) ...
		+ S6 * (C1*C5*S4 * qd1 + S1 * (C2p3*C4*C5 - S2p3*S5) * qd1 + C4*C5*S1 * qd4 - S1*S4*S5 * qd5 ...
		+ C1 * (C4*C5*S2p3 * (qd2 + qd3) + C2p3*S5 * (qd2 + qd3) + C2p3*C5*S4 * qd4 + C5*S2p3 * qd5 ...
		+ C2p3*C4*S5 * qd5)) + C6 * (C5*S1*S4 + C1 * (-(C2p3*C4*C5) + S2p3*S5)) * qd6 + (C4*S1 + C1*C2p3*S4) * S6 * qd6;
	R_dot(1,3) = -(C1*S4*S5 * qd1) - S1 * (C5*S2p3 + C2p3*C4*S5) * qd1 - C4*S1*S5 * qd4 - C5*S1*S4 * qd5 ...
		+ C1 * (C2p3*C5 * (qd2 + qd3) - C4*S2p3*S5 * (qd2 + qd3) - C2p3*S4*S5 * qd4 + C2p3*C4*C5 * qd5 - S2p3*S5 * qd5);
	R_dot(2,1) = -(C1*C6*S2p3*S5 * qd1) - S1 * (C5*C6*S4 + C4*S6) * qd1 + C1*C2p3 * (C4*C5*C6 - S4*S6) * qd1 ...
		- C2p3*C6*S1*S5 * (qd2 + qd3) - S1*S2p3 * (C4*C5*C6 - S4*S6) * (qd2 + qd3) - C5*C6*S1*S2p3 * qd5 + S1*S2p3*S5*S6 * qd6 ...
		- C2p3*S1 * ((C5*C6*S4 + C4*S6) * qd4 + C4*C6*S5 * qd5 + (C6*S4 + C4*C5*S6) * qd6) + C1 * ((C4*C5*C6 - S4*S6) * qd4 ...
		- C6*S4*S5 * qd5 + (C4*C6 - C5*S4*S6) * qd6);
	R_dot(2,2) = C1*S2p3*S5*S6 * qd1 - C1*C2p3 * (C6*S4 + C4*C5*S6) * qd1 + S1 * (-(C4*C6) + C5*S4*S6) * qd1 ...
		+ C2p3*S1*S5*S6 * (qd2 + qd3) + S1*S2p3 * (C6*S4 + C4*C5*S6) * (qd2 + qd3) + C5*S1*S2p3*S6 * qd5 ...
		+ C6*S1*S2p3*S5 * qd6 - C1 * ((C6*S4 + C4*C5*S6) * qd4 - S4*S5*S6 * qd5 + (C5*C6*S4 + C4*S6) * qd6) ...
		- C2p3*S1 * ((C4*C6 - C5*S4*S6) * qd4 - C4*S5*S6 * qd5 + (C4*C5*C6 - S4*S6) * qd6);
	R_dot(2,3) = C1*C5*S2p3 * qd1 + C2p3*C5*S1 * (qd2 + qd3) + S5 * ((C1*C2p3*C4 - S1*S4) * qd1 ...
		- C4*S1*S2p3 * (qd2 + qd3) + (C1*C4 - C2p3*S1*S4) * qd4) + C5 * (C2p3*C4*S1 + C1*S4) * qd5 - S1*S2p3*S5 * qd5;
	R_dot(3,1) = C2p3*S4*S6 * (qd2 + qd3) + C4*S2p3*S6 * qd4 - C6 * (C2p3*C4*C5 * (qd2 + qd3) - S2p3*S5 * (qd2 + qd3) ...
		- C5*S2p3*S4 * qd4 + C2p3*C5 * qd5 - C4*S2p3*S5 * qd5) + C6*S2p3*S4 * qd6 + (C4*C5*S2p3 + C2p3*S5) * S6 * qd6;
	R_dot(3,2) = C2p3*C6*S4 * (qd2 + qd3) + C4*C6*S2p3 * qd4 + S6 * (C2p3*C4*C5 * (qd2 + qd3) - S2p3*S5 * (qd2 + qd3) ...
		- C5*S2p3*S4 * qd4 + C2p3*C5 * qd5 - C4*S2p3*S5 * qd5) + C6 * (C4*C5*S2p3 + C2p3*S5) * qd6 - S2p3*S4*S6 * qd6;
	R_dot(3,3) = -(C5*S2p3 * (qd2 + qd3)) - C2p3*C4*S5 * (qd2 + qd3) + S2p3*S4*S5 * qd4 - C4*C5*S2p3 * qd5 ...
		- C2p3*S5 * qd5;

end