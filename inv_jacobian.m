function J_eInv = inv_jacobian(a_i,d_i,d_e,q_pos)

    a2 = a_i(2);
    a3 = a_i(3);
    d2 = d_i(2);
    d4 = d_i(4);
    d6 = d_i(6) + d_e;

    C1 = cos(q_pos(1));
    C2 = cos(q_pos(2));
    C3 = cos(q_pos(3));
    C4 = cos(q_pos(4));
    C5 = cos(q_pos(5));

    S1 = sin(q_pos(1));
    S2 = sin(q_pos(2));
    S3 = sin(q_pos(3));
    S4 = sin(q_pos(4));
    S5 = sin(q_pos(5));

    C2sq = C2^2;
    C3sq = C3^2;
    C4sq = C4^2;
    C2cb = C2^3;

    Sd2 = sin(2*q_pos(2));
    Sd3 = sin(2*q_pos(3));
    Sd4 = sin(2*q_pos(4));

    S2sq = S2^2;
    S3sq = S3^2;
    S4sq = S4^2;
    S2cb = S2^3;
    S3cb = S3^3;

    C2p3	= cos(q_pos(2)+q_pos(3));
    C2p3sq	= cos(q_pos(2)+q_pos(3))^2;
    S2p3	= sin(q_pos(2)+q_pos(3));
    Sd2p3	= sin(2*(q_pos(2)+q_pos(3)));
    S2p3sq	= sin(q_pos(2)+q_pos(3))^2;

    Csc3	= 1/sin(q_pos(3));
    Csc3h	= 1/sin(q_pos(3)/2);
    Csc5	= 1/sin(q_pos(5));
    Cot3	= 1/tan(q_pos(3));
    Cot5	= 1/tan(q_pos(5));
    Sec3h	= 1/cos(q_pos(3)/2);

    Csc3sq = (1/sin(q_pos(3)))^2;
    Csc3cb = (1/sin(q_pos(3)))^3;
    Cot3sq = (1/tan(q_pos(3)))^2;

    J_eInv = zeros(6,6);

    J_eInv(1,1) = -(S1 / (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(2,1) = (Csc3*S2p3 * (C1 - (d2 * S1) / (a2 + a3 * S2 + d4 * S2p3))) / a3;
    J_eInv(3,1) = -((Csc3 * (a3 * S2 + d4 * S2p3) * (-(d2 * S1) + C1 * (a2 + a3 * S2 + d4 * S2p3))) ...
                / (a3 * d4 * (a2 + a3 * S2 + d4 * S2p3)));
    J_eInv(4,1) = (d4 * (-1 + C4*Cot3*Cot5) * S1*S2*S3 + d4 * C2*S1 * (C3 + C4*Cot5*S3) - Cot5*Csc3*S2 ...
                * (-(d2 * S1) + C1 * (a2 + a3 * S2 + d4 * S2p3)) * S4) / (d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(5,1) = (C1*C4*Csc3*S2 + (S1 * (-(d2 * C4*Csc3*S2) + d4 * S2p3*S4)) / (a2 + a3 * S2 + d4 * S2p3)) / d4;
    J_eInv(6,1) = (Csc5 * (-(d4 * C4*S1*S2p3) + Csc3*S2 * (-(d2 * S1) + C1 * (a2 + a3 * S2 + d4 * S2p3)) * S4)) ...
                / (d4 * (a2 + a3 * S2 + d4 * S2p3));

    J_eInv(1,2) = C1 / (a2 + a3 * S2 + d4 * S2p3);
    J_eInv(2,2) = (Csc3*S2p3 * (S1 + (d2 * C1) / (a2 + a3 * S2 + d4 * S2p3))) / a3;
    J_eInv(3,2) = -((Csc3 * (a3 * S2 + d4 * S2p3) * (d2 * C1 + S1 * (a2 + a3 * S2 + d4 * S2p3))) ...
                / (a3 * d4 * (a2 + a3 * S2 + d4 * S2p3)));
    J_eInv(4,2) = (Csc3 * (-(Cot5*S1*S2*S4) - (C1 * (d4 * S3 * (S2 * (C3*C4*Cot5 - S3) + C2 * (C3 + C4*Cot5*S3)) ...
                + d2 * Cot5*S2*S4)) / (a2 + a3 * S2 + d4 * S2p3))) / d4;
    J_eInv(5,2) = (C4*Csc3*S1*S2 + (C1 * (d2 * C4*Csc3*S2 - d4 * S2p3*S4)) / (a2 + a3 * S2 + d4 * S2p3)) / d4;
    J_eInv(6,2) = (Csc5 * (d4 * C1*C4*S2p3 + Csc3*S2 * (d2 * C1 + S1 * (a2 + a3 * S2 + d4 * S2p3)) * S4)) ...
                / (d4 * (a2 + a3 * S2 + d4 * S2p3));

    J_eInv(1,3) = 0.0;
    J_eInv(2,3) = (C2p3*Csc3) / a3;
    J_eInv(3,3) = -(((a3 * C2 + d4 * C2p3) * Csc3) / (a3 * d4));
    J_eInv(4,3) = -((C2*Cot5*Csc3*S4) / d4);
    J_eInv(5,3) = (C2*C4*Csc3) / d4;
    J_eInv(6,3) = (C2*Csc3*Csc5*S4) / d4;

    J_eInv(1,4) = (d6 * C1 * (C2p3*C5 - C4*S2p3*S5)) / (a2 + a3 * S2 + d4 * S2p3);
    J_eInv(2,4) = (d6 * Csc3 * (d2 * C1*C5*Sd2p3 - 2. * (C4 * (d2 * C1*S2p3sq + S1 * (a2 + a3 * S2 + d4 * S2p3)) ...
                + C1*C2p3 * (a2 + a3 * S2 + d4 * S2p3) * S4) * S5)) / (2. * a3 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(3,4) = (d6 * (S1 * (a3 * C5 + (d4 + a3 * C3) * C4*Csc3*S5) +	(C1*Csc3h*Sec3h * (-(d2 * C2p3*C5 ...
                * (a3 * S2 + d4 * S2p3)) + d2 * C4*S2p3 * (a3 * S2 + d4 * S2p3) * S5 + (a3 * C2 + d4 * C2p3) ...
                * (a2 + a3 * S2 + d4 * S2p3) * S4*S5)) / (2. * (a2 + a3 * S2 + d4 * S2p3)))) / (a3 * d4);
    J_eInv(4,4) = (Cot5*S1*S4 * (d4 + d6 * C5 + d6 * C4*Cot3*S5) + (C1 * (d4 * C3sq * (d4 + d6 * C4sq*C5) * S2sq ...
                + a2*d4 * C4*Cot5*S2*S3 + a3*d4 * C4*Cot5*S2sq*S3 -	d4*d6 * C4sq*C5*S2sq*S3sq ...
                + d4 * C2sq * (-(d6 * C3sq*C4sq*C5) - C3*C4* (d4 + d6 * C5) * Cot5*S3 + (d4 + d6 * C5) * S3sq) ...
                + d4*d6 * C4sq*C5*Sd2*Sd3 + d2*d6 * C4*C5*Cot3*S2sq*S4 + d2*d6 * C5*Cot5*S2sq*S4 - d4*d6 * C5*S2sq*S3sq*S4sq ...
                + C2 * (d4 * C4 * (-(C3*Cot5 * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2)) + C4 * (a2 + a3 * S2) * S3 ...
                + (d4 + d6 * C5) * Cot5*S2*S3sq) + d2*d6 * C5 * (C4 - Cot3*Cot5) * S2*S4 + (d6 * C3*C5*Cot3 ...
                * (a2 + (a3 + d4 * C3) * S2) + (3 * d4*d6 * C3*C5*S2 + (d4 + d6 * C5) * (a2 + a3 * S2)) * S3) * S4sq) ...
                + d4 * C3 * (C4 * (C4*S2 * (a2 + a3 * S2) + ((d4 + d6 * C5) * Cot5*S2sq + d4 * C4*Sd2) * S3) ...
                + (S2 * (a2 + a3 * S2) + d4 * Sd2*S3) * S4sq) + d4*d6 * C2p3*C4*S2p3*S5)) / (a2 + a3 * S2 + d4 * S2p3)) / d4;
    J_eInv(5,4) = (S3sq * (-(d4 * C2cb*C4*Csc3*S1 * (d4 + d6 * C5 + d6 * C4*Cot3*S5)) -	C2sq * (C4*Csc3*S1 ...
                * (d4 * Cot3*S2 + Csc3 * (a2 + a3 * S2)) + d4 * C1*Cot3*S4) * (d4 + d6 * C5 + d6 * C4*Cot3*S5) ...
                + S2 * (-(C4*Csc3sq*S1*S2 * (a2 + (a3 + d4 * C3) * S2) * (d4 + d6 * C5 + d6 * C4*Cot3*S5)) ...
                + C1 * (d4 * ((d4 + d6 * C5) * Cot3*S2 + Csc3 * (a2 + a3 * S2)) * S4 - d2*d6 * C4sq*Cot3*Csc3sq*S2*S5 ...
                + d6 * C4*S2 * (-(d2 * C5*Csc3sq) + d4 * Cot3sq*S4*S5))) - C2 * (d4 * C4*Csc3*S1*S2sq ...
                * (d4 + d6 * C5 + d6 * C4*Cot3*S5) + C1 * (d4 * (a2 * Cot3*Csc3 + ((d4 + d6 * C5) * (-1 + Cot3sq) ...
                + a3 * Cot3*Csc3) * S2) * S4 + d2*d6 * C4sq*Csc3sq*S2*S5 + d6 * C4 * (-(d2 * C5*Cot3*Csc3sq*S2) ...
                + (d4 * Cot3 * (-1 + Cot3sq) * S2 + Csc3cb * (a2 + a3 * S2)) * S4*S5))))) /	(d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(6,4) = (-((d6 * C4*Cot3 + d6 * Cot5 + d4 * Csc5) * S1*S4) + (C1 * (d4 * C2sq*C4*S3 * (C3 * (d4 + d6 * C5) * Csc5 ...
                - d6 * C4*S3) +	S2 * (-(d4 * C4 * (d6 * C3sq*C4*S2 + Csc5 * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2) * S3)) ...
                - d2*d6 * (C4*Cot3 + Cot5) * S2*S4) + C2 * (d4 * C4 * (C3*Csc5 * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2) ...
                - 2 * d6 * C3*C4*S2*S3 - (d4 + d6 * C5) * Csc5*S2*S3sq) + d2*d6 * (-C4 + Cot3*Cot5) * S2*S4 ...
                - d6 * Csc3 * (a2 + a3 * S2 + d4 * S2p3) * S4sq))) / (a2 + a3 * S2 + d4 * S2p3)) / d4;

    J_eInv(1,5) = (d6 * S1 * (C2p3*C5 - C4*S2p3*S5)) / (a2 + a3 * S2 + d4 * S2p3);
    J_eInv(2,5) = (d6 * Csc3h*Sec3h * (2 * C1*C4 * (a2 + a3 * S2 + d4 * S2p3) * S5 + S1 * (d2 * C5*Sd2p3 - 2 ...
                * (d2 * C4*S2p3sq + C2p3 * (a2 + a3 * S2 + d4 * S2p3) * S4) * S5))) / (4. * a3 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(3,5) = (d6 * (-(C1 * (a3 * C5 + (d4 + a3 * C3) * C4*Csc3*S5)) + (Csc3*S1 * (-(d2 * C2p3*C5 * (a3 * S2 + d4 * S2p3)) ...
                + (d2 * C4*S2p3 * (a3 * S2 + d4 * S2p3) + (a3 * C2 + d4 * C2p3) * (a2 + a3 * S2 + d4 * S2p3) * S4) * S5)) ...
                / (a2 + a3 * S2 + d4 * S2p3))) / (a3*d4);
    J_eInv(4,5) = (d4 * C3sq* (d4 + d6 * C4sq*C5) * S1*S2sq + a2*d4 * C4*Cot5*S1*S2*S3 + a3*d4 * C4*Cot5*S1*S2sq*S3 ...
                - d4*d6 * C4sq*C5*S1*S2sq*S3sq + d4*d6 * C4sq*C5*S1*Sd2*Sd3 - a2*d6 * C1*C4*C5*Cot3*S2sq*S4 ...
                - a2*d4 * C1*Cot5*S2sq*S4 - a2*d6 * C1*C5*Cot5*S2sq*S4 + d2*d6 * C4*C5*Cot3*S1*S2sq*S4 ...
                + d2*d6 * C5*Cot5*S1*S2sq*S4 - a3*d6 * C1*C4*C5*Cot3*S2cb*S4 - a3*d4 * C1*Cot5*S2cb*S4 ...
                - a3*d6 * C1*C5*Cot5*S2cb*S4 - d4 * C1*C2cb * (d6 * C3*C4*C5 + (d4 + d6 * C5) * Cot5*S3) * S4 ...
                - d4*d6 * C5*S1*S2sq*S3sq*S4sq + C2sq * (d4 * C4*S1 * (-(d6 * C3sq*C4*C5) - C3 * (d4 + d6 * C5) * Cot5*S3 ...
                + C4 * (d4 + d6 * C5) * S3sq) -	C1 * (d4 * Cot5 + d6 * C5 * (C4*Cot3 + Cot5)) * (a2 + (a3 + d4 * C3) * S2) * S4 ...
                + d4 * (d4 + d6 * C5) * S1*S3sq*S4sq) +	C2 * (d4 * C4*S1 * (-(C3*Cot5 * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2)) ...
                + C4 * (a2 + a3 * S2) * S3 + (d4 + d6 * C5) * Cot5*S2*S3sq) - S2 * (d6 * C3sq*C5 * (d2 * (-C4 + Cot3*Cot5) * S1 ...
                + d4 * C1*C3*C4*S2) + Cot5 * (d2*d6 * C3*C5*S1 + d4 * C1 * (d4 + d6 * C3sq*C5) * S2) * S3 ...
                + d6 * C4*C5 * (-(d2 * S1) + d4 * C1*C3*S2) * S3sq + d4*d6 * C1*C5*Cot5*S2*S3cb) * S4 ...
                + S1 * (d6 * C3*C5*Cot3 * (a2 + (a3 + d4 * C3) * S2) ...
                + (3 * d4*d6 * C3*C5*S2 + (d4 + d6 * C5) * (a2 + a3 * S2)) * S3) * S4sq) ...
                + d4 * C3 * (C4*S1 * (C4*S2 * (a2 + a3 * S2) + ((d4 + d6 * C5) * Cot5*S2sq + d4 * C4*Sd2) * S3) ...
                - C1 * (d4 * Cot5 + d6 * C5 * (C4*Cot3 + Cot5)) * S2cb*S4 + S1 * (S2 * (a2 + a3 * S2) + d4 * Sd2*S3) * S4sq) ...
                + d4*d6 * C2p3*C4*S1*S2p3*S5) / (d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(5,5) = (C1*C4 * (d4 + d6 * C5 + d6 * C4*Cot3*S5) + (S1 *	(2 * C2p3 * (d2*d6 * C4*C5*Csc3*S2 - d4 * (a2 + a3 * S2) * S4) ...
                - 2 * d6 * C4*Csc3 * (d2 * C4*S2*S2p3 + C2 * (a2 + a3 * S2) * S4) * S5 - d4 * Sd2p3*S4 * (d4 + d6 * C5 ...
                + d6 * C4*Cot3*S5))) / (2. * (a2 + a3 * S2 + d4 * S2p3))) / d4;
    J_eInv(6,5) = (d4 * C2sq*C4*S1*S3 * (C3 * (d4 + d6 * C5) * Csc5 - d6 * C4*S3) -	d4 * C4*S1*S2 * (d6 * C3sq*C4*S2 + Csc5 ...
                * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2) * S3) + (-(d2*d6 * (C4*Cot3 + Cot5) * S1*S2sq) + C1 * (d6 * C4*Cot3 ...
                + d6 * Cot5 + d4 * Csc5) * (a2 + a3 * S2 + d4 * S2p3)) * S4 + C2*S1 * (d4 * C4 * (C3*Csc5 * (a2 + (a3 + C3 ...
                * (d4 + d6 * C5)) * S2) - 2 * d6 * C3*C4*S2*S3 - (d4 + d6 * C5) * Csc5*S2*S3sq) + d2*d6 * (-C4 + Cot3*Cot5) ...
                * S2*S4 - d6 * Csc3 * (a2 + a3 * S2 + d4 * S2p3) * S4sq)) / (d4 * (a2 + a3 * S2 + d4 * S2p3));

    J_eInv(1,6) = -((d6 * (C5*S2p3 + C2p3*C4*S5)) / (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(2,6) = (d6 * Csc3*S2p3 * (-(d2 * C5*S2p3) + (-(d2 * C2p3*C4) + (a2 + a3 * S2 + d4 * S2p3) * S4) * S5)) ...
                / (a3 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(3,6) = (d6 * Csc3 * (a3 * S2 + d4 * S2p3) * (d2 * C5*S2p3 + (d2 * C2p3*C4 - (a2 + a3 * S2 + d4 * S2p3) * S4) * S5)) ...
                / (a3*d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(4,6) = (d4 * C2sq*S3 * (C3 * (d4 + d6 * (1 + C4sq) * C5) + C4 * (d4 + d6 * C5) * Cot5*S3) + S2*S3 ...
                * (-(d4 * C4sq * (a2 + a3 * S2)) - d2*d6 * C4*C5*S2*S3*S4 - (d4 + d6 * C5) * (a2 + a3 * S2) * S4sq) + C2 ...
                * (d4 * (C3 * (a2 + (a3 + d4 * C3) * S2) + C4*Cot5 * (a2 + a3 * S2) * S3 - C4sq * (d4 + 2 * d6 * C5) * S2*S3sq) ...
                + d2*d6 * C5 * (C4*Cot3 + Cot5) * S2*S4 - d4 * (d4 + 2 * d6 * C5) * S2*S3sq*S4sq) +	C3 * (d4 * C4 ...
                * (2 * d6 * C2p3*C4*C5*S2 + Cot5*S2 * (a2 + a3 * S2) + (-(d4 * C4*S2sq) + (d4 + d6 * C5) * Cot5*Sd2) * S3) ...
                + d2*d6 * C5*Cot5*S2sq*S3*S4 - S2 * (d6 * C5*Cot3 * (a2 + a3 * S2) + d4 * (d4 + 2 * d6 * C5) * S2*S3) * S4sq) ...
                + C3sq*S2sq * (d6 * C5*Cot3*S4 * (d2 * Cot5 - d4 * S4) + C4 * (d4 * (d4 + d6 * C5) * Cot5 - d2*d6 * C5*S4)) ...
                + d4*d6 * C2p3sq*C4*S5) / (d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(5,6) = (d4 * C3 * (S2 * (a2 + (a3 + C3 * (d4 + d6 * C5)) * S2) + (d4 + d6 * C5) * Sd2*S3) * S4 + d2*d6 * C4sq*S2sq*S5 ...
                + d4 * C2sq*S3*S4 * ((d4 + d6 * C5) * S3 + d6 * C3*C4*S5) +	d6 * C4*S2 * (-(d2 * C5*Cot3*S2) ...
                + (d4 * C3sq*Cot3*S2 + Csc3 * (a2 + a3 * S2)) * S4*S5) +	C2 * (-(d2*d6 * C4*C5*S2) + d4 * (a2 + a3 * S2) ...
                * S3*S4 - d2*d6 * C4sq*Cot3*S2*S5 +	d4*d6 * C3sq*S2*Sd4*S5)) / (d4 * (a2 + a3 * S2 + d4 * S2p3));
    J_eInv(6,6) = (-(d4 * C2sq*C4*S3 * (d6 * C3*C4 + (d4 + d6 * C5) * Csc5*S3)) + C2 * (-(d4 * C4 * (d6 * C3sq*C4*S2 + Csc5 ...
                * (a2 + (a3 + 2 * C3 * (d4 + d6 * C5)) * S2) * S3 - d6 * C4*S2*S3sq)) -	d2*d6 * (C4*Cot3 + Cot5) * S2*S4) + S2 ...
                * (-(d4 * C3*C4 * (Csc5 * (a2 + (a3 + d4 * C3) * S2) + d6 * S2 * (C3 * Cot5 - C4*S3))) + d2*d6 * (C4 - Cot3*Cot5) ...
                * S2*S4 + d6 * Csc3 * (a2 + a3 * S2 + d4 * S2p3) * S4sq)) / (d4 * (a2 + a3 * S2 + d4 * S2p3));

end